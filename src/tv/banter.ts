/** Sacs mélangés : chaque phrase sort une fois avant de pouvoir revenir. */
const bags = new Map<string, string[]>();

export function banter(kind: keyof typeof BANTER | string, lang: Lang, family: boolean, vars: Record<string, string | number> = {}): string {
  const all = BANTER[kind]?.[lang] ?? BANTER[kind]?.fr ?? [];
  // Pas de phrase qui parle d'un joueur absent (ex. {p} vide)
  const missing = ['n', 'p', 'k', 'G', 'c', 't', 'e'].filter((k) => !vars[k] && vars[k] !== 0);
  const pool = all.filter((l) => !(family && l.startsWith('!')) && !missing.some((k) => l.includes(`{${k}}`)));
  if (!pool.length) return '';
  const key = `${kind}|${lang}|${family}|${missing.join('')}`;
  let bag = bags.get(key);
  if (!bag || !bag.length) {
    bag = [...pool].sort(() => Math.random() - 0.5);
    bags.set(key, bag);
  }
  let line = bag.pop()!.replace(/^!/, '');
  for (const [k, v] of Object.entries(vars)) line = line.split(`{${k}}`).join(String(v));
  return line;
}
